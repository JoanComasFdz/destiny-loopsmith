using System.Collections.Frozen;
using System.Collections.Immutable;
using System.Text.Json;
using Loopsmith.Functional;
using static Loopsmith.ManifestTools.Core.DefinitionReading;

namespace Loopsmith.ManifestTools.Core;

/// <summary>
/// rules/manifest.yaml's text (<see cref="Text"/>), the line that says what it holds (<see cref="Summary"/>) and every hash
/// Loopsmith names that the manifest doesn't have (<see cref="Missing"/>: reported, not written).
/// </summary>
public sealed record Excerpt(string Text, string Summary, ImmutableArray<long> Missing);

/// <summary>
/// Bungie's manifest and the hashes Loopsmith names → rules/manifest.yaml, Loopsmith's excerpt of the manifest
/// (docs/rule-format.md, "Manifest"; what it holds: tools/manifest/README.md). The output is sorted and stable, so a rerun
/// on the same manifest changes nothing.
/// </summary>
public static class ExcerptWriting
{
    private static readonly FrozenDictionary<long, string> Tiers =
        new Dictionary<long, string> { [2] = "basic", [3] = "common", [4] = "rare", [5] = "legendary", [6] = "exotic" }.ToFrozenDictionary();

    private static readonly FrozenDictionary<long, string> DamageTypes = new Dictionary<long, string>
    {
        [1] = "kinetic", [2] = "arc", [3] = "solar", [4] = "void", [6] = "stasis", [7] = "strand",
    }.ToFrozenDictionary();

    /// <summary><c>equippingBlock.ammoType</c>; 0 is none.</summary>
    private static readonly FrozenDictionary<long, string> AmmoTypes =
        new Dictionary<long, string> { [1] = "primary", [2] = "special", [3] = "heavy" }.ToFrozenDictionary();

    /// <summary>An item's classType (3: any class).</summary>
    private static readonly FrozenDictionary<long, string> ClassTypes =
        new Dictionary<long, string> { [0] = "titan", [1] = "hunter", [2] = "warlock" }.ToFrozenDictionary();

    private static readonly ImmutableArray<string> Header =
    [
        "# Loopsmith's excerpt of the Bungie manifest (docs/rule-format.md, \"Manifest\"): names, descriptions, icons,",
        "# slots, perks and armor sets for every hash the rules and tools/manifest/test-items.yaml name, and every plug that",
        "# changes an armor stat (statPlugs: for adding up a player's own armor, as DIM does). Generated by",
        "# tools/manifest/Loopsmith.ManifestTools - don't edit by hand, rerun it. Bungie's data, used under its API terms.",
    ];

    public static Result<Excerpt, string> WriteExcerpt(ManifestComponents manifest, NamedHashes named, string version) =>
        FindCategory(manifest.SocketCategories, "WEAPON PERKS").Bind(perkCategory =>
        FindCategory(manifest.SocketCategories, "WEAPON MODS").Bind(modCategory =>
        FindCategory(manifest.SocketCategories, "INTRINSIC TRAITS").Bind(weaponIntrinsics =>
        FindCategory(manifest.SocketCategories, "ARMOR PERKS").Bind(armorIntrinsics =>
        WriteExcerpt(manifest, named, version, new Categories(perkCategory, modCategory, weaponIntrinsics, armorIntrinsics))))));

    private sealed record Categories(long Perks, long Mods, long WeaponIntrinsics, long ArmorIntrinsics);

    /// <summary>What an item's entry needs beyond its own definition: what was read of every named item.</summary>
    private sealed record EntryContext(
        ManifestComponents Manifest,
        long PerkCategory,
        FrozenDictionary<long, long> Intrinsics,
        FrozenDictionary<long, long> WeaponCatalysts,
        FrozenSet<long> Catalysts,
        FrozenDictionary<long, ImmutableArray<long>> SubclassPlugs,
        FrozenDictionary<long, ImmutableArray<long>> WeaponMods);

    private static Result<Excerpt, string> WriteExcerpt(ManifestComponents manifest, NamedHashes named, string version, Categories categories)
    {
        var items = manifest.Items;
        var plugsByCategory = items.Entries
            .Select(pair => (Hash: long.Parse(pair.Key, System.Globalization.CultureInfo.InvariantCulture), Category: ItemReading.ReadPlugCategory(pair.Value)))
            .Where(plug => plug.Category.Length > 0)
            .OrderBy(plug => plug.Hash)
            .GroupBy(plug => plug.Category)
            .ToFrozenDictionary(group => group.Key, group => group.Select(plug => plug.Hash).ToImmutableArray());
        var setOfPerk = manifest.ItemSets.Entries
            .SelectMany(pair => ReadArray(pair.Value, "setPerks").Select(perk => (Perk: ReadNumber(perk, "sandboxPerkHash"), Set: pair.Key)))
            .Where(pair => pair.Perk.IsSome())
            .GroupBy(pair => ((Optional<long>.Some)pair.Perk).Value)
            .ToFrozenDictionary(group => group.Key, group => ParseHash(group.Last().Set));

        var namedAll = named.RuleHashes.Union(named.TestItemHashes);
        var namedItems = namedAll.Where(items.HasDefinition).ToImmutableHashSet();
        var definitions = namedItems.ToFrozenDictionary(hash => hash, hash => FindItem(items, hash));
        var kinds = namedItems.ToFrozenDictionary(hash => hash, hash => ItemReading.ClassifyItem(definitions[hash], manifest.Buckets).Kind);
        var weapons = namedItems.Where(hash => kinds[hash] == "weapon").ToImmutableHashSet();
        var traits = weapons
            .SelectMany(hash => ItemReading.ReadTraits(definitions[hash], manifest.SocketTypes, categories.Perks, manifest.PlugSets).UnwrapOr([]))
            .SelectMany(column => column)
            .ToImmutableHashSet();
        var intrinsics = namedItems
            .Where(hash => kinds[hash] is "weapon" or "armor")
            .Select(hash => (Hash: hash, Plug: ItemReading.ReadIntrinsic(definitions[hash], kinds[hash] == "weapon" ? categories.WeaponIntrinsics : categories.ArmorIntrinsics, items)))
            .Where(pair => pair.Plug.IsSome())
            .ToFrozenDictionary(pair => pair.Hash, pair => ((Optional<long>.Some)pair.Plug).Value);
        var weaponCatalysts = weapons
            .Select(hash => (Hash: hash, Plug: ItemReading.ReadCatalyst(definitions[hash], manifest.SocketTypes, plugsByCategory, items, manifest.Perks)))
            .Where(pair => pair.Plug.IsSome())
            .ToFrozenDictionary(pair => pair.Hash, pair => ((Optional<long>.Some)pair.Plug).Value);
        var weaponMods = weapons
            .Select(hash => (Hash: hash, Mods: ItemReading.ReadMods(definitions[hash], manifest.SocketTypes, categories.Mods, manifest.PlugSets, items)))
            .Where(pair => !pair.Mods.IsEmpty)
            .ToFrozenDictionary(pair => pair.Hash, pair => pair.Mods);
        var catalysts = weaponCatalysts.Values.ToFrozenSet();
        var catalystPerks = catalysts.SelectMany(plug => ItemReading.ReadGrantedPerks(FindItem(items, plug), manifest.Perks)).ToImmutableHashSet();
        var wantedSets = namedItems
            .Where(hash => kinds[hash] == "armor")
            .Select(hash => ReadObject(definitions[hash], "equippingBlock").Bind(block => ReadSetNumber(block, "equipableItemSetHash")))
            .OfType<Optional<long>.Some>().Select(some => some.Value)
            .Concat(namedAll.Where(setOfPerk.ContainsKey).Select(hash => setOfPerk[hash]))
            .ToImmutableHashSet();
        var missingSets = wantedSets.Where(hash => !manifest.ItemSets.HasDefinition(hash)).Order().ToImmutableArray();
        if (!missingSets.IsEmpty)
        {
            return new Result<Excerpt, string>.Error($"The armor set {missingSets[0]} isn't in DestinyEquipableItemSetDefinition.json.");
        }

        var setPerks = wantedSets
            .SelectMany(hash => ReadArray(FindItem(manifest.ItemSets, hash), "setPerks").Select(perk => ReadNumber(perk, "sandboxPerkHash")))
            .OfType<Optional<long>.Some>().Select(some => some.Value)
            .ToImmutableHashSet();
        // every artifact with perk sockets (Artifacts 2.0: the seven the designer's artifact editor offers) and all its perks
        var artifacts = items.Entries
            .Where(pair => ReadString(pair.Value, "itemTypeDisplayName").UnwrapOr("") == "Artifact"
                && !ItemReading.ReadArtifactPerks(pair.Value, manifest.PlugSets, manifest.SocketTypes).IsEmpty)
            .Select(pair => ParseHash(pair.Key))
            .ToImmutableHashSet();
        var artifactPerks = artifacts
            .SelectMany(hash => ItemReading.ReadArtifactPerks(FindItem(items, hash), manifest.PlugSets, manifest.SocketTypes))
            .Where(items.HasDefinition)
            .ToImmutableHashSet();
        // what a subclass can hold: its plugs (the designer's subclass editor offers them), but the empty sockets'
        var subclassPlugs = namedItems
            .Where(hash => kinds[hash] == "subclass")
            .ToFrozenDictionary(hash => hash, hash => ItemReading.ReadSubclassPlugs(definitions[hash], manifest.PlugSets)
                .Where(plug => items.FindDefinition(plug).Match(found => !ReadName(found.Value).StartsWith("Empty", StringComparison.Ordinal), _ => false))
                .ToImmutableArray());
        // every enhanced plug of a trait the rules author (by its name: a weapon's enhanced copy, a crafted one), so the C#
        // catalog can tell an authored perk that lacks its enhanced trait (docs/rule-format.md, "Enhanced traits")
        var traitNames = named.RuleHashes
            .Select(items.FindDefinition)
            .OfType<Optional<JsonElement>.Some>().Select(some => some.Value)
            .Where(item => ReadString(item, "itemTypeDisplayName").UnwrapOr("") is "Trait" or "Origin Trait")
            .Select(ReadName)
            .ToImmutableHashSet();
        var enhancedTraits = items.Entries
            .Where(pair => ReadString(pair.Value, "itemTypeDisplayName").UnwrapOr("") is "Enhanced Trait" or "Enhanced Origin Trait"
                && ReadString(ReadDisplay(pair.Value), "name") is Optional<string>.Some name && traitNames.Contains(name.Value))
            .Select(pair => ParseHash(pair.Key))
            .ToImmutableHashSet();
        var context = new EntryContext(manifest, categories.Perks, intrinsics, weaponCatalysts, catalysts, subclassPlugs, weaponMods);

        var wantedItems = namedItems.Union(traits).Union(intrinsics.Values).Union(catalysts).Union(artifacts).Union(artifactPerks)
            .Union(enhancedTraits).Union(subclassPlugs.Values.SelectMany(plugs => plugs)).Union(weaponMods.Values.SelectMany(mods => mods))
            .Order().ToImmutableArray();
        var wantedPerks = namedAll.Except(namedItems).Where(manifest.Perks.HasDefinition).Union(catalystPerks).Union(setPerks)
            .Order().ToImmutableArray();
        var missingNamed = namedAll.Except(namedItems).Except(wantedPerks).Order();

        var armorStats = StatPlugReading.ArmorStats
            .Select(stat => (stat.Hash, stat.Stat, Display: manifest.Stats.FindDefinition(stat.Hash).Map(ReadDisplay).UnwrapOr(EmptyObject)))
            .ToImmutableArray();
        var missingStats = armorStats.Where(stat => ReadText(stat.Display, "icon") is Optional<string>.None).Select(stat => stat.Hash);
        var wantedTraits = named.RuleTraits.Order().ToImmutableArray();
        var traitDisplays = wantedTraits
            .Select(hash => (Hash: hash, Display: manifest.Traits.FindDefinition(hash).Map(ReadDisplay).UnwrapOr(EmptyObject)))
            .Select(trait => (trait.Hash, Name: ReadText(trait.Display, "name"), Icon: ReadText(trait.Display, "icon")))
            .ToImmutableArray();
        var missingTraits = traitDisplays.Where(trait => !trait.Name.IsSome() || !trait.Icon.IsSome()).Select(trait => trait.Hash);
        var constants = manifest.ItemConstants.Entries.Select(pair => pair.Value).FirstOrDefault(EmptyObject);

        ImmutableArray<(long Hash, string Line)> entries =
        [
            .. wantedItems.Select(hash => (hash, WriteItemEntry(hash, FindItem(items, hash), context))),
            .. wantedPerks.Select(hash => (hash, WritePerkEntry(hash, FindItem(manifest.Perks, hash)))),
        ];
        var statPlugs = items.Entries
            .Select(pair => (Hash: ParseHash(pair.Key), Item: pair.Value, Kind: StatPlugReading.ClassifyStatPlug(pair.Value)))
            .Where(plug => plug.Kind.IsSome())
            .OrderBy(plug => plug.Hash)
            .Select(plug => StatPlugReading.WriteStatPlugEntry(plug.Hash, plug.Item, ((Optional<string>.Some)plug.Kind).Value))
            .ToImmutableArray();

        ImmutableArray<string> lines =
        [
            .. Header,
            $"version: {TextWriting.QuoteText(version)}",
            "damageTypes:",
            .. manifest.DamageTypes.Entries
                .Select(pair => pair.Value)
                .OrderBy(definition => ReadNumber(definition, "enumValue").UnwrapOr(0))
                .Select(definition => (Name: ReadNumber(definition, "enumValue").Bind(value => DamageTypes.TryGetValue(value, out var name) ? Optional.Some(name) : Optional.None<string>()),
                    Icon: ReadText(ReadDisplay(definition), "icon")))
                .Where(type => type.Name.IsSome() && type.Icon.IsSome())
                .Select(type => $"  - {{ type: {type.Name.UnwrapOr("")}, icon: {type.Icon.UnwrapOr("")} }}"),
            "breakerTypes:",
            .. manifest.BreakerTypes.Entries
                .OrderBy(pair => ReadNumber(pair.Value, "enumValue").UnwrapOr(0))
                .Select(pair => (Hash: pair.Key, Display: ReadDisplay(pair.Value)))
                .Where(breaker => ReadText(breaker.Display, "icon").IsSome())
                .Select(breaker => $"  - {{ hash: {breaker.Hash}, name: {TextWriting.ToText(ReadString(breaker.Display, "name").UnwrapOr(""))}, icon: {ReadText(breaker.Display, "icon").UnwrapOr("")} }}"),
            "armorStats:",
            .. armorStats
                .Where(stat => ReadText(stat.Display, "icon").IsSome())
                .Select(stat => $"  - {{ stat: {stat.Stat}, name: {TextWriting.ToText(ReadString(stat.Display, "name").UnwrapOr(""))}, icon: {ReadText(stat.Display, "icon").UnwrapOr("")} }}"),
            "itemConstants:",
            "  tierOverlays: [" + string.Join(", ", ReadArray(constants, "gearTierOverlayImagePaths").Select(ReadJsonText)) + "]",
            .. new[] { ("masterworkOverlayPath", "masterworkOverlay"), ("masterworkExoticOverlayPath", "masterworkExoticOverlay") }
                .Select(pair => (Written: pair.Item2, Path: ReadText(constants, pair.Item1)))
                .Where(pair => pair.Path.IsSome())
                .Select(pair => $"  {pair.Written}: {pair.Path.UnwrapOr("")}"),
            "keywordTraits:",
            .. traitDisplays
                .Where(trait => trait.Name.IsSome() && trait.Icon.IsSome())
                .Select(trait => $"  - {{ hash: {trait.Hash}, name: {TextWriting.ToText(trait.Name.UnwrapOr(""))}, icon: {trait.Icon.UnwrapOr("")} }}"),
            "armorSets:",
            .. wantedSets.Order().Select(hash => WriteSetEntry(hash, FindItem(manifest.ItemSets, hash))),
            "items:",
            .. entries.OrderBy(entry => entry.Hash).ThenBy(entry => entry.Line, StringComparer.Ordinal).Select(entry => entry.Line),
            "statPlugs:",
            .. statPlugs,
        ];
        return new Result<Excerpt, string>.Ok(new Excerpt(
            string.Join("\n", lines) + "\n",
            $"wrote {entries.Length} items, {wantedSets.Count} armor sets and {statPlugs.Length} stat plugs to rules/manifest.yaml",
            [.. missingNamed, .. missingStats, .. missingTraits]));
    }

    /// <summary>An item's entry: its name, kind, type, tier, slot and what else the excerpt says of its kind.</summary>
    private static string WriteItemEntry(long hash, JsonElement item, EntryContext context)
    {
        var manifest = context.Manifest;
        var display = ReadDisplay(item);
        var classified = ItemReading.ClassifyItem(item, manifest.Buckets);
        var kind = context.Catalysts.Contains(hash) ? "catalyst" : classified.Kind;
        var equipping = ReadObject(item, "equippingBlock").UnwrapOr(EmptyObject);
        var breaker = ReadSetNumber(item, "breakerTypeHash").Match(
            own => Optional.Some(own.Value),
            _ => context.Intrinsics.TryGetValue(hash, out var intrinsic)
                ? ItemReading.ReadFrameBreaker(manifest.Items.FindDefinition(intrinsic).UnwrapOr(EmptyObject), manifest.Perks, manifest.BreakerTypes)
                : Optional.None<long>());
        var columns = kind == "weapon"
            ? ItemReading.ReadTraits(item, manifest.SocketTypes, context.PerkCategory, manifest.PlugSets)
            : Optional.None<ImmutableArray<ImmutableArray<long>>>();
        var granted = kind == "catalyst" ? ItemReading.ReadGrantedPerks(item, manifest.Perks) : [];
        var (tiers, slots) = kind == "artifact"
            ? ItemReading.ReadArtifactTiers(item, manifest.PlugSets, manifest.SocketTypes)
            : (ImmutableArray<ImmutableArray<long>>.Empty, ImmutableArray<int>.Empty);
        var description = ItemReading.ReadDescription(item, manifest.Perks);
        ImmutableArray<(string Key, Optional<string> Value)> fields =
        [
            ("hash", Optional.Some(ToKey(hash))),
            ("name", Optional.Some(TextWriting.ToText(ReadString(display, "name").UnwrapOr("")))),
            ("kind", Optional.Some(kind)),
            ("type", ReadText(item, "itemTypeDisplayName").Map(TextWriting.ToText)),
            ("tier", ReadObject(item, "inventory").Bind(inventory => ReadNumber(inventory, "tierType")).Bind(Find(Tiers))),
            ("slot", classified.Slot.Bind(slot => slot != "general" ? Optional.Some(slot) : Optional.None<string>())),
            ("damageType", kind == "weapon" ? ReadNumber(item, "defaultDamageType").Bind(Find(DamageTypes)) : Optional.None<string>()),
            ("ammo", kind == "weapon" ? ReadNumber(equipping, "ammoType").Bind(Find(AmmoTypes)) : Optional.None<string>()),
            ("breaker", kind == "weapon" ? breaker.Map(ToKey) : Optional.None<string>()),
            ("traits", columns.Map(found => WriteList(found.Select(column => WriteList(column))))),
            ("intrinsic", context.Intrinsics.TryGetValue(hash, out var intrinsicPlug) ? Optional.Some(ToKey(intrinsicPlug)) : Optional.None<string>()),
            ("catalyst", context.WeaponCatalysts.TryGetValue(hash, out var catalyst) ? Optional.Some(ToKey(catalyst)) : Optional.None<string>()),
            ("mods", context.WeaponMods.TryGetValue(hash, out var mods) ? Optional.Some(WriteList(mods)) : Optional.None<string>()),
            ("set", kind == "armor" ? ReadSetNumber(equipping, "equipableItemSetHash").Map(ToKey) : Optional.None<string>()),
            ("class", kind == "armor" ? ReadNumber(item, "classType").Bind(Find(ClassTypes)) : Optional.None<string>()),
            ("perks", granted.IsEmpty ? Optional.None<string>() : Optional.Some(WriteList(granted))),
            ("tiers", tiers.IsEmpty ? Optional.None<string>() : Optional.Some(WriteList(tiers.Select(tier => WriteList(tier))))),
            ("slots", tiers.IsEmpty ? Optional.None<string>() : Optional.Some("[" + string.Join(", ", slots) + "]")),
            ("flavor", tiers.IsEmpty ? Optional.None<string>() : ReadText(item, "flavorText").Map(TextWriting.ToText)),
            ("plugs", kind == "subclass" && context.SubclassPlugs.TryGetValue(hash, out var plugs) && !plugs.IsEmpty ? Optional.Some(WriteList(plugs)) : Optional.None<string>()),
            ("description", description.Length > 0 ? Optional.Some(TextWriting.ToText(description)) : Optional.None<string>()),
            ("watermark", kind is "weapon" or "armor" ? ReadText(item, "iconWatermark") : Optional.None<string>()),
            ("icon", ReadText(display, "icon")),
        ];
        return WriteFlowEntry(fields);
    }

    /// <summary>A sandbox perk (a catalyst's or an armor set's): name, Bungie's description, icon; it has no item type.</summary>
    private static string WritePerkEntry(long hash, JsonElement perk)
    {
        var display = ReadDisplay(perk);
        ImmutableArray<(string Key, Optional<string> Value)> fields =
        [
            ("hash", Optional.Some(ToKey(hash))),
            ("name", Optional.Some(TextWriting.ToText(ReadString(display, "name").UnwrapOr("")))),
            ("kind", Optional.Some("perk")),
            ("description", ReadText(display, "description").Map(TextWriting.ToText)),
            ("icon", ReadText(display, "icon")),
        ];
        return WriteFlowEntry(fields);
    }

    /// <summary>An armor set: its name and the perk each piece count grants (<c>pieces: 2</c> → its 2-piece perk).</summary>
    private static string WriteSetEntry(long hash, JsonElement itemSet)
    {
        var perks = ReadArray(itemSet, "setPerks")
            .OrderBy(perk => ReadNumber(perk, "requiredSetCount").UnwrapOr(0))
            .Select(perk => $"{{ pieces: {ReadJsonText(ReadField(perk, "requiredSetCount").UnwrapOr(EmptyObject))}, perk: {ReadJsonText(ReadField(perk, "sandboxPerkHash").UnwrapOr(EmptyObject))} }}");
        return $"  - {{ hash: {hash}, name: {TextWriting.ToText(ReadName(itemSet))}, perks: [{string.Join(", ", perks)}] }}";
    }

    private static string WriteFlowEntry(IEnumerable<(string Key, Optional<string> Value)> fields) =>
        "  - { " + string.Join(", ", fields
            .Where(field => field.Value.IsSome())
            .Select(field => $"{field.Key}: {field.Value.UnwrapOr("")}")) + " }";

    private static string WriteList(IEnumerable<long> hashes) => "[" + string.Join(", ", hashes.Select(ToKey)) + "]";

    private static string WriteList(IEnumerable<string> written) => "[" + string.Join(", ", written) + "]";

    /// <summary>A JSON value as the excerpt writes it bare: a text as it is, anything else as the JSON writes it.</summary>
    private static string ReadJsonText(JsonElement value) =>
        value.ValueKind == JsonValueKind.String ? value.GetString()! : value.GetRawText();

    private static Func<long, Optional<string>> Find(FrozenDictionary<long, string> names) =>
        value => names.TryGetValue(value, out var name) ? Optional.Some(name) : Optional.None<string>();

    /// <summary>The first socket category of that name (the excerpt can't be read without it).</summary>
    private static Result<long, string> FindCategory(ManifestTable categories, string name) =>
        categories.Entries
            .Where(pair => ReadName(pair.Value) == name)
            .Select(pair => Optional.Some(ParseHash(pair.Key)))
            .FirstOrDefault(Optional.None<long>())
            .ToResult(() => $"DestinySocketCategoryDefinition.json has no socket category named {name}.");

    /// <summary>A definition known to be there (its hash came from the same table).</summary>
    private static JsonElement FindItem(ManifestTable table, long hash) => table.FindDefinition(hash).UnwrapOr(EmptyObject);

    private static long ParseHash(string key) => long.Parse(key, System.Globalization.CultureInfo.InvariantCulture);
}
